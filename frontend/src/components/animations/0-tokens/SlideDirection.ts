/**
 * SlideDirection — the direction a SlideIn element enters from.
 * - "up": element starts 20px below (translates up into position) — most common
 * - "down": element starts 20px above (translates down)
 * - "left": element starts 20px to the right (translates left)
 * - "right": element starts 20px to the left (translates right)
 */
export type SlideDirection = "up" | "down" | "left" | "right";
